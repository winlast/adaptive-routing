#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Проверяет, что журналы разных серверов читаются одинаково.

Каждый образец в formats/ описывает одни и те же два обращения. Значит,
какой бы сервер их ни записал, на выходе обязаны получиться одни и те же
адрес, параметр и длительность. Если формат разобрался иначе — это
ошибка разбора, а не особенность формата.

Отдельно проверяется отказ: журнал без времени ответа должен не просто
не разобраться, а получить объяснение, что делать. Молчаливый отказ —
самая дорогая ошибка продукта.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from loadlens import read_log, diagnose_log  # noqa: E402

FORMATS = Path(__file__).resolve().parent / "formats"

# Что обязан дать каждый образец: маршрут, параметр limit, длительность в мс.
ОЖИДАЕТСЯ = [("/api/search", 10.0, 12.0), ("/api/search", 900.0, 740.0)]
ДОПУСК_МС = 0.5

# Журналы, которые разбираться не должны, и чем им обязаны ответить.
ОТКАЗЫ = {"nginx_no_time.log": "нет времени ответа"}


def main() -> int:
    проблемы = []
    проверено = 0

    for путь in sorted(FORMATS.glob("*")):
        if путь.suffix == ".md":
            continue
        проверено += 1
        запросы = read_log(путь)

        if путь.name in ОТКАЗЫ:
            if запросы:
                проблемы.append(f"{путь.name}: разобрался, хотя не должен")
                continue
            подсказка = diagnose_log(путь)
            если_нужно = ОТКАЗЫ[путь.name]
            if если_нужно not in подсказка:
                проблемы.append(
                    f"{путь.name}: отказ без объяснения «{если_нужно}»")
            else:
                print(f"{путь.name:<24} отказ с объяснением — как и нужно")
            continue

        if len(запросы) != len(ОЖИДАЕТСЯ):
            проблемы.append(
                f"{путь.name}: разобрано {len(запросы)}, "
                f"ожидалось {len(ОЖИДАЕТСЯ)}")
            continue

        ошибки = []
        for запрос, (маршрут, лимит, мс) in zip(запросы, ОЖИДАЕТСЯ):
            if запрос.path != маршрут:
                ошибки.append(f"маршрут {запрос.path!r} вместо {маршрут!r}")
            if запрос.params.get("limit") != лимит:
                ошибки.append(f"параметры {запрос.params} вместо limit={лимит}")
            if abs(запрос.duration_ms - мс) > ДОПУСК_МС:
                ошибки.append(f"{запрос.duration_ms:.1f} мс вместо {мс} мс")
        if ошибки:
            проблемы.append(f"{путь.name}: " + "; ".join(ошибки))
        else:
            print(f"{путь.name:<24} разобран верно")

    print(f"\nФорматов проверено: {проверено}")
    if проблемы:
        print(f"ОШИБОК: {len(проблемы)}")
        for p in проблемы:
            print("  •", p)
        return 1
    print("Все форматы дают одинаковый результат.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
