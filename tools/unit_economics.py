#!/usr/bin/env python3
"""
Во что обходится разница в ёмкости, измеренная на стенде.

Считается только то, что опирается на замер: во сколько раз меньше
экземпляров нужно, чтобы выдержать заданную нагрузку, не нарушая
обещания по времени отклика. Перевод в рубли сделан по публичному
прейскуранту и по явно названному предположению о размере экземпляра —
предположение отделено от измерения намеренно.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Публичный прейскурант Yandex Cloud, платформа Intel Ice Lake,
# уровень производительности 100 %, цены с НДС, проверено 20.09.2026.
ЦЕНА_VCPU_ЧАС = 1.24
ЦЕНА_ГБ_ЧАС = 0.33
ЧАСОВ_В_МЕСЯЦЕ = 720

# Предположение, а не измерение: размер одного экземпляра приложения.
# Читатель может подставить свой — отношение числа экземпляров от этого
# не изменится, оно взято из замера.
VCPU_НА_ЭКЗЕМПЛЯР = 4
ГБ_НА_ЭКЗЕМПЛЯР = 8

# Нагрузка, для которой считается пример.
ЦЕЛЕВЫЕ_РПС = 1000


def main() -> None:
    cap = json.loads((ROOT / "data" / "nginx_capacity.json")
                     .read_text(encoding="utf-8"))
    цена_экземпляра = ЧАСОВ_В_МЕСЯЦЕ * (
        VCPU_НА_ЭКЗЕМПЛЯР * ЦЕНА_VCPU_ЧАС + ГБ_НА_ЭКЗЕМПЛЯР * ЦЕНА_ГБ_ЧАС)

    out = {
        "источник_цен": "Yandex Cloud, Intel Ice Lake 100 %, с НДС, "
                        "проверено 20.09.2026",
        "цена_vcpu_час_руб": ЦЕНА_VCPU_ЧАС,
        "цена_гб_час_руб": ЦЕНА_ГБ_ЧАС,
        "предположение_экземпляр": f"{VCPU_НА_ЭКЗЕМПЛЯР} vCPU, "
                                   f"{ГБ_НА_ЭКЗЕМПЛЯР} ГБ",
        "цена_экземпляра_руб_мес": round(цена_экземпляра),
        "целевая_нагрузка_рпс": ЦЕЛЕВЫЕ_РПС,
        "по_порогам": {},
    }

    for порог in cap["порог_p95_мс"]:
        ключ = str(порог)
        строка = {}
        for режим, данные in cap["режимы"].items():
            ёмкость = данные["ёмкость_при_пороге"][ключ]
            if not ёмкость:
                строка[режим] = None
                continue
            экземпляров = math.ceil(ЦЕЛЕВЫЕ_РПС / ёмкость["рпс"])
            строка[режим] = {
                "ёмкость_рпс": ёмкость["рпс"],
                "ёмкость_интерполирована": ёмкость["оценка"],
                "экземпляров": экземпляров,
                "руб_в_месяц": round(экземпляров * цена_экземпляра),
            }
        обычная = строка.get("обычная (least_conn)")
        наша = строка.get("по оценке стоимости")
        if обычная and наша:
            разница = обычная["руб_в_месяц"] - наша["руб_в_месяц"]
            строка["разница"] = {
                "экземпляров_меньше": обычная["экземпляров"] - наша["экземпляров"],
                "руб_в_месяц": разница,
                "руб_в_год": разница * 12,
                "доля_%": round(разница / обычная["руб_в_месяц"] * 100, 1),
            }
        out["по_порогам"][ключ] = строка

    путь = ROOT / "data" / "unit_economics.json"
    путь.write_text(json.dumps(out, ensure_ascii=False, indent=2),
                    encoding="utf-8")
    print(json.dumps(out, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
